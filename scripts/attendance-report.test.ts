import assert from 'node:assert/strict';
import { attendanceDate, attendanceDays, attendanceSummary, calendarDays, monthBounds } from '../src/domain/attendanceReport';
import { buildAttendanceWorkbook } from '../src/services/attendanceExport';
import { seedData } from '../src/data/seed';
import type { AttendanceEntry, User } from '../src/types';
import ExcelJS from 'exceljs';

const employees:User[]=[{id:'a',name:'Asha',initials:'A',title:'Architect',access:'employee',authUid:'uid-a',tone:'#000'},{id:'b',name:'Bina',initials:'B',title:'Architect',access:'employee',authUid:'uid-b',tone:'#000'}];
const admin:User={...employees[0],id:'admin',access:'admin'};
const entry=(id:string,date:string,start:string,end?:string):AttendanceEntry=>({id,userId:'a',clockInAt:`${date}T${start}:00+05:30`,clockOutAt:end?`${date}T${end}:00+05:30`:undefined});
const entries=[entry('1','2026-01-01','09:00','13:00'),entry('2','2026-01-01','14:00','19:00'),entry('3','2026-01-02','09:00','17:59'),entry('4','2026-01-03','09:00','18:00'),entry('5','2026-01-03','19:00')];
const before=JSON.stringify(entries);
const rows=attendanceDays(employees,entries,'2026-01-01','2026-01-04');
assert.equal(rows.length,8,'every employee/date is represented, including no-record days');
assert.equal(rows[0].hours,9,'split shifts exclude the lunch gap');
assert.equal(rows[0].complete,true);
assert.ok(rows[2].hours<9,'8h59m does not round up to nine');
assert.equal(rows[4].complete,false,'closed nine-hour shift plus open shift remains incomplete');
assert.equal(rows[4].checkOut,undefined);
assert.equal(rows[6].status,'Missing check-in / check-out');
const summary=attendanceSummary(rows.filter(row=>row.user.id==='a'));
assert.deepEqual([summary.days,summary.complete,summary.ninePlus,summary.underNine,summary.incomplete],[4,2,1,1,2]);
assert.ok(Math.abs(summary.total-(27-1/60))<1e-9);
assert.ok(Math.abs(summary.average-(9+(9-1/60))/2)<1e-9,'average excludes partial/incomplete days');
assert.equal(JSON.stringify(entries),before,'reporting never modifies backend records');
assert.equal(calendarDays('2024-02-01','2024-02-29').length,29);
assert.equal(monthBounds('2025-02').end,'2025-02-28');
assert.deepEqual(monthBounds('2025-12','2026-01'),{start:'2025-12-01',end:'2026-01-31'});
assert.equal(calendarDays('2025-12-01','2026-01-31').length,62);
assert.throws(()=>calendarDays('2026-02-30','2026-03-01'));
assert.throws(()=>calendarDays('2026-02-02','2026-02-01'));
assert.throws(()=>monthBounds('2026-13'));
assert.equal(attendanceDate('2026-01-01T18:29:59Z'),'2026-01-01');
assert.equal(attendanceDate('2026-01-01T18:30:00Z'),'2026-01-02','studio midnight changes date without relying on device timezone');
const overnight=[{id:'night',userId:'a',clockInAt:'2026-01-01T22:00:00+05:30',clockOutAt:'2026-01-02T07:00:00+05:30'}];
assert.equal(attendanceDays(employees,overnight,'2026-01-01','2026-01-02')[0].hours,9);
assert.equal(attendanceDays(employees,overnight,'2026-01-01','2026-01-02')[2].entries.length,0,'overnight shift belongs to check-in date');
const invalid=[entry('invalid','2026-01-01','09:00','08:00')];
assert.equal(attendanceDays(employees,invalid,'2026-01-01','2026-01-01')[0].complete,false);

const data={...seedData,users:[...employees,admin],attendanceEntries:entries};
await assert.rejects(()=>buildAttendanceWorkbook(data,employees[0],'','2026-01-01','2026-01-04'),/Only admins/);
const workbook=await buildAttendanceWorkbook(data,admin,'','2026-01-01','2026-01-04');
const buffer=await workbook.xlsx.writeBuffer(),saved=new ExcelJS.Workbook();await saved.xlsx.load(buffer);
const sheet=saved.getWorksheet('Attendance')!;
assert.ok(sheet.getCell('B5').value instanceof Date,'matrix columns have typed dates');
assert.equal((sheet.getCell('E5').value as Date).toISOString().slice(0,10),'2026-01-04');
assert.equal(sheet.getCell('A6').value,'Asha');assert.equal(sheet.getCell('A7').value,'Bina');
assert.equal(sheet.getCell('B6').numFmt,'[h]:mm');
assert.equal((sheet.getCell('B6').value as Date).getTime()-Date.UTC(1899,11,30),9*3600000);
assert.match(String(sheet.getCell('D6').value),/Incomplete/);
assert.equal(sheet.getCell('E6').value,'Missing');
assert.equal(sheet.getCell('B7').value,'Missing');
assert.ok(sheet.getCell('B6').note,'shift details preserved in cell notes');
assert.equal((sheet.getCell('B6').fill as ExcelJS.FillPattern).fgColor?.argb,'FFDCEEDD');
assert.equal((sheet.getCell('C6').fill as ExcelJS.FillPattern).fgColor?.argb,'FFFFE4C4');
assert.equal((sheet.getCell('D6').fill as ExcelJS.FillPattern).fgColor?.argb,'FFF0F2F3');
assert.equal(sheet.getCell('A11').value,'Asha');assert.equal(sheet.getCell('B11').value,4);assert.equal(sheet.getCell('C11').value,2);
assert.equal(sheet.getCell('A13').value,'All Employees');assert.equal(sheet.getCell('B13').value,8);
for(const row of [5,6,7,10,11,13]){
  for(let col=1;col<=(row>=10?8:5);col++){
    const cell=sheet.getRow(row).getCell(col);
    for(const side of ['top','bottom','left','right'] as const)assert.equal(cell.border[side]?.style,'thin','all table and summary cells retain borders after saving');
    assert.equal(cell.font.name,'Aptos');
  }
}
assert.equal(sheet.views[0].showGridLines,false);
assert.equal(sheet.pageSetup.orientation,'landscape');
assert.equal(sheet.pageSetup.fitToWidth,0,'wide matrices print across pages without shrinking to illegible text');
assert.equal((sheet.views[0] as ExcelJS.WorksheetViewFrozen).xSplit,1);
assert.equal((sheet.getCell('A13').fill as ExcelJS.FillPattern).fgColor?.argb,'FF20372F');
const detailed=await buildAttendanceWorkbook(data,admin,'a','2026-01-01','2026-01-04');
assert.ok(detailed.getWorksheet('Attendance')!.getCell('A6').value instanceof Date);
assert.equal(detailed.getWorksheet('Attendance')!.getCell('D6').numFmt,'dd mmm hh:mm');
assert.equal(detailed.getWorksheet('Attendance')!.getCell('F6').value,9/24);
const yearBoundary=await buildAttendanceWorkbook(data,admin,'','2025-12-31','2026-01-02');
assert.equal((yearBoundary.getWorksheet('Attendance')!.getCell('D5').value as Date).toISOString().slice(0,10),'2026-01-02');
const single=await buildAttendanceWorkbook(data,admin,'b','2026-01-01','2026-01-04');
assert.equal(single.getWorksheet('Attendance')!.getCell('C6').value,'Bina');
assert.equal(single.getWorksheet('Attendance')!.getCell('G6').value,'Missing check-in / check-out');
console.log('Attendance calculations, permissions, date boundaries, and Excel round-trip tests passed.');
